#!/usr/bin/env node
'use strict';

/**
 * Generates packages/ai/src/prompts/apx-reference.md: the list of `apx.*` members the scripting assistant
 * may use, read from the REAL runtime (packages/core/src/script-runtime.js, by introspection) so the prompt
 * cannot drift from the API or invent a member.
 *
 *   node scripts/gen-apx-reference.js          write the file
 *   node scripts/gen-apx-reference.js --check  exit 1 when the committed file is stale
 *
 * Not listed on purpose: members a model-written script may not use (network and flow control, refused by
 * the script screen) and apx.db (needs a configured database connection).
 */

const fs = require('fs');
const path = require('path');
const { getApxSurface, signature, isRefusedName } = require('../packages/ai/src/apx-surface');

const OUT = path.join(__dirname, '..', 'packages', 'ai', 'src', 'prompts', 'apx-reference.md');
const EXCLUDED_TOP_LEVEL = new Set(['db']);

const HEADER = [
  '<!-- GENERATED by scripts/gen-apx-reference.js from packages/core/src/script-runtime.js. Do not edit: run `npm run gen:apx-reference`. -->',
  '# apx scripting API (generated)',
  '',
  'Scripts are plain JavaScript run by Apilix after (tests) or before (pre-request) a request. The global `apx` is the only API; `pm` is an alias of it.',
  'Use only the members listed here. Anything else does not exist and makes the script fail.',
  '',
].join('\n');

function leaves(node, prefix, out) {
  for (const [name, child] of Object.entries(node.children || {})) {
    if (isRefusedName(name)) continue;
    const p = `${prefix}.${name}`;
    if (child.kind === 'fn') {
      out.push(`- \`${prefix}.${signature(name, child.params)}\``);
      leaves(child, p, out);
    } else if (child.kind === 'obj') {
      leaves(child, p, out);
    } else {
      out.push(`- \`${p}\` (${child.type})`);
    }
  }
  return out;
}

function generate() {
  const { tree, expect } = getApxSurface();
  const lines = [HEADER];
  const top = Object.entries(tree.children);

  lines.push('## Functions', '');
  for (const [name, child] of top) {
    if (child.kind !== 'fn' || isRefusedName(name)) continue;
    lines.push(`- \`apx.${signature(name, child.params)}\``);
    for (const [sub, c2] of Object.entries(child.children || {})) lines.push(`- \`apx.${name}.${signature(sub, c2.params)}\``);
  }
  lines.push('');

  for (const [name, child] of top) {
    if (child.kind === 'fn' || EXCLUDED_TOP_LEVEL.has(name) || isRefusedName(name)) continue;
    const body = child.kind === 'obj' ? leaves(child, `apx.${name}`, []) : [`- \`apx.${name}\` (${child.type})`];
    if (!body.length) continue; // everything under it is refused in generated scripts
    lines.push(`## apx.${name}`, '', ...body, '');
  }

  lines.push('## Assertions: apx.expect(value) and apx.softExpect(value)', '');
  lines.push('Chainable words (no effect): ' + expect.props.filter(p => !['ok', 'true', 'false', 'null', 'undefined', 'NaN', 'exist', 'empty', 'positive', 'negative', 'integer', 'finite'].includes(p) && p !== 'not').map(p => `\`${p}\``).join(', ') + '.');
  lines.push('Negation: `not`.');
  lines.push('Assertion properties (no call): ' + ['ok', 'true', 'false', 'null', 'undefined', 'NaN', 'exist', 'empty', 'positive', 'negative', 'integer', 'finite'].filter(p => expect.props.includes(p)).map(p => `\`${p}\``).join(', ') + '.');
  lines.push('Assertion methods:', '');
  for (const m of expect.methods) lines.push(`- \`.${signature(m.name, m.params)}\``);
  if (expect.deep) lines.push('', 'After `deep` (for example `.to.deep.equal(x)`): ' + expect.deep.map(k => `\`${k}\``).join(', ') + '.');
  lines.push('', 'Example: `apx.test("status is 200", () => { apx.expect(apx.response.code).to.equal(200); });`', '');
  return lines.join('\n');
}

module.exports = { generate, OUT };

if (require.main === module) {
  const text = generate();
  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, 'utf8') : '';
    if (current !== text) {
      console.error('packages/ai/src/prompts/apx-reference.md is stale: run `npm run gen:apx-reference`.');
      process.exit(1);
    }
    console.log('apx-reference.md is up to date.');
  } else {
    fs.writeFileSync(OUT, text);
    console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
  }
}
