import { vi, describe, it, expect } from 'vitest';

// codeGen -> hurlUtils imports the store (which touches window); stub it like docsExport.test does.
vi.mock('../store', () => ({ generateId: () => 'mock-id' }));

import type { AppCollection } from '../types';
import { buildAiRows, rowsToDescriptions } from './docsAiRows';
import { exportCollectionDocs, maskCollectionForAi } from './docsExport';

const collection = {
  info: { name: 'Shop', description: '' },
  item: [
    { id: 'f1', name: 'Orders', item: [
      { id: 'r1', name: 'List', request: { method: 'GET', url: { raw: 'https://api.test/orders?limit=10', query: [{ key: 'limit', value: '10' }] } } },
    ] },
  ],
} as unknown as AppCollection;

const answer = {
  __collection__: { description: 'Shop API.' },
  f1: { description: 'Orders.' },
  r1: { description: 'Lists orders.', params: { limit: 'Max rows.' } },
  unknown: { description: 'dropped: no such entry' },
};

describe('buildAiRows', () => {
  it('maps ids to labelled rows and ignores unknown ids', () => {
    const rows = buildAiRows(collection, undefined, answer);
    expect(rows.map(r => r.id)).toEqual(['__collection__', 'f1', 'r1']);
    expect(rows[2].label).toBe('Orders / GET List');
    expect(rows[2].params).toEqual({ limit: 'Max rows.' });
    expect(rows.every(r => r.included)).toBe(true);
  });

  it('skips empty suggestions', () => {
    expect(buildAiRows(collection, undefined, { r1: { description: '', params: {} } })).toEqual([]);
  });
});

describe('rowsToDescriptions', () => {
  it('keeps included rows, trims, drops blanks, and reflects user edits', () => {
    const rows = buildAiRows(collection, undefined, answer);
    rows[1].included = false;
    rows[2].description = '  Edited by user.  ';
    rows[2].params.limit = '   ';
    const d = rowsToDescriptions(rows);
    expect(d.f1).toBeUndefined();
    expect(d.r1).toEqual({ description: 'Edited by user.' });
    expect(d.__collection__).toEqual({ description: 'Shop API.' });
  });

  it('feeds exportCollectionDocs: AI text appears and is marked, and can be unmarked', () => {
    const descriptions = rowsToDescriptions(buildAiRows(collection, undefined, answer));
    const on = exportCollectionDocs(collection, { format: 'markdown', descriptions });
    expect(on.content).toContain('Lists orders.');
    expect(on.content).toContain('Description generated by AI');
    const off = exportCollectionDocs(collection, { format: 'markdown', descriptions, markAiContent: false });
    expect(off.content).toContain('Lists orders.');
    expect(off.content).not.toContain('generated by AI');
  });
});

describe('maskCollectionForAi', () => {
  it('masks known secret values and leaves the original untouched', () => {
    const c = { info: { name: 'x' }, item: [{ id: 'a', name: 'a', request: { method: 'GET', url: 'https://x/?k=SUPER-SECRET-1' } }] } as unknown as AppCollection;
    const masked = maskCollectionForAi(c, new Set(['SUPER-SECRET-1']));
    expect(JSON.stringify(masked)).not.toContain('SUPER-SECRET-1');
    expect(JSON.stringify(c)).toContain('SUPER-SECRET-1');
    expect(maskCollectionForAi(c, new Set())).toBe(c);
  });
});
