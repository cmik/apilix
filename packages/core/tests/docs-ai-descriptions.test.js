'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { generateDocs, buildDocModel } = require('../src/docs');

const collection = () => ({
  info: { name: 'Shop', description: '' },
  item: [
    {
      id: 'f1',
      name: 'Orders',
      item: [
        {
          id: 'r1',
          name: 'List orders',
          request: {
            method: 'GET',
            url: { raw: 'https://api.test/orders?limit=10', query: [{ key: 'limit', value: '10' }, { key: 'status', value: 'open', description: 'Human text' }] },
            header: [{ key: 'X-Trace', value: 'abc' }],
          },
        },
        {
          id: 'r2',
          name: 'Create order',
          request: {
            method: 'POST',
            description: 'Written by a human',
            url: 'https://api.test/orders',
            body: { mode: 'urlencoded', urlencoded: [{ key: 'sku', value: 'A1' }] },
          },
        },
      ],
    },
  ],
});

const descriptions = {
  __collection__: { description: 'Shop API.' },
  f1: { description: 'Everything about orders.' },
  r1: { description: 'Lists orders.', params: { limit: 'Max rows.', status: 'AI should not win', 'X-Trace': 'Trace id.' } },
  r2: { description: 'AI should not win', params: { sku: 'Product SKU.' } },
};

test('no descriptions option → model unchanged', () => {
  const m = buildDocModel(collection(), {});
  assert.equal(m.requests[0].description, '');
  assert.equal(m.requests[0].descriptionSource, undefined);
});

test('AI descriptions fill gaps and are tagged source=ai', () => {
  const m = buildDocModel(collection(), { descriptions });
  const [r1] = m.requests;
  assert.equal(r1.description, 'Lists orders.');
  assert.equal(r1.descriptionSource, 'ai');
  assert.equal(r1.query.find(q => q.key === 'limit').description, 'Max rows.');
  assert.equal(r1.query.find(q => q.key === 'limit').descriptionSource, 'ai');
  assert.equal(r1.headers[0].description, 'Trace id.');
  assert.equal(m.description, 'Shop API.');
  assert.equal(m.tree[0].description, 'Everything about orders.');
  assert.equal(m.tree[0].descriptionSource, 'ai');
  assert.equal(m.requests[1].body.fields[0].description, 'Product SKU.');
});

test('a human description always wins over the AI one', () => {
  const m = buildDocModel(collection(), { descriptions });
  const status = m.requests[0].query.find(q => q.key === 'status');
  assert.equal(status.description, 'Human text');
  assert.equal(status.descriptionSource, undefined);
  assert.equal(m.requests[1].description, 'Written by a human');
  assert.equal(m.requests[1].descriptionSource, undefined);
});

test('ignores malformed descriptions input', () => {
  for (const bad of [null, 'x', 5, [], { r1: 'nope' }, { r1: { description: 42, params: 'x' } }]) {
    assert.doesNotThrow(() => buildDocModel(collection(), { descriptions: bad }));
  }
});

test('markdown marks AI content, and can be turned off', () => {
  const on = generateDocs(collection(), { format: 'markdown', descriptions }).content;
  assert.match(on, /Lists orders\./);
  assert.match(on, /Description generated by AI/);
  assert.match(on, /Max rows\. _\(AI\)_/);
  assert.doesNotMatch(on, /Written by a human\s*\n+_Description generated by AI/);
  const off = generateDocs(collection(), { format: 'markdown', descriptions, markAiContent: false }).content;
  assert.match(off, /Lists orders\./);
  assert.doesNotMatch(off, /generated by AI|\(AI\)/);
});

test('html marks AI content, and can be turned off', () => {
  const on = generateDocs(collection(), { format: 'html', descriptions }).content;
  assert.match(on, /Lists orders\./);
  assert.match(on, /class="ai"/);
  const off = generateDocs(collection(), { format: 'html', descriptions, markAiContent: false }).content;
  assert.match(off, /Lists orders\./);
  assert.doesNotMatch(off, /<span class="ai"/);
});

test('openapi adds x-generated-by only on AI-filled descriptions', () => {
  const { spec } = generateDocs(collection(), { format: 'openapi', descriptions });
  const get = spec.paths['/orders'].get;
  assert.equal(get.description, 'Lists orders.');
  assert.equal(get['x-generated-by'], 'ai');
  const limit = get.parameters.find(p => p.name === 'limit');
  assert.equal(limit['x-generated-by'], 'ai');
  assert.equal(get.parameters.find(p => p.name === 'status')['x-generated-by'], undefined);
  const post = spec.paths['/orders'].post;
  assert.equal(post['x-generated-by'], undefined);
  const schema = post.requestBody.content['application/x-www-form-urlencoded'].schema;
  assert.equal(schema.properties.sku.description, 'Product SKU.');
  assert.equal(schema.properties.sku['x-generated-by'], 'ai');
  const off = generateDocs(collection(), { format: 'openapi', descriptions, markAiContent: false }).spec;
  assert.equal(off.paths['/orders'].get['x-generated-by'], undefined);
});
